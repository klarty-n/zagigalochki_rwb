"""Generate reviewable, set-based PostgreSQL SQL from the agreed core contract.

Run after changing the mapping, then review model/02_load.sql. No DB access.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def col(name, source=None, kind="text", required=False):
    return (name, source or name, kind, required)


TABLES = [
    ("customers", "customers", ["customer_id"], [
        col("customer_id", required=True), col("customer_unique_id", required=True),
        col("zip_code_prefix", "customer_zip_code_prefix"), col("city", "customer_city"), col("state", "customer_state")], []),
    ("sellers", "sellers", ["seller_id"], [col("seller_id", required=True),
        col("zip_code_prefix", "seller_zip_code_prefix"), col("city", "seller_city"), col("state", "seller_state")], []),
    ("categories", None, ["category_name"], [col("category_name", required=True), col("category_name_english")], []),
    ("products", "products", ["product_id"], [col("product_id", required=True), col("category_name", "product_category_name"),
        col("name_length", "product_name_lenght", "integer"), col("description_length", "product_description_lenght", "integer"),
        col("photos_qty", "product_photos_qty", "integer"), col("weight_g", "product_weight_g", "numeric(12,2)"),
        col("length_cm", "product_length_cm", "numeric(12,2)"), col("height_cm", "product_height_cm", "numeric(12,2)"),
        col("width_cm", "product_width_cm", "numeric(12,2)")], [("category_name", "categories", "category_name")]),
    ("orders", "orders", ["order_id"], [col("order_id", required=True), col("customer_id", required=True),
        col("order_status", required=True), col("order_purchase_at", "order_purchase_timestamp", "timestamp", True),
        col("order_approved_at", kind="timestamp"), col("delivered_carrier_at", "order_delivered_carrier_date", "timestamp"),
        col("delivered_customer_at", "order_delivered_customer_date", "timestamp"),
        col("estimated_delivery_date", "order_estimated_delivery_date", "date")], [("customer_id", "customers", "customer_id")]),
    ("order_items", "order_items", ["order_id", "order_item_id"], [col("order_id", required=True),
        col("order_item_id", kind="integer", required=True), col("product_id", required=True), col("seller_id", required=True),
        col("shipping_limit_at", "shipping_limit_date", "timestamp", True), col("price", kind="numeric(12,2)", required=True),
        col("freight_value", kind="numeric(12,2)", required=True)],
        [("order_id", "orders", "order_id"), ("product_id", "products", "product_id"), ("seller_id", "sellers", "seller_id")]),
    ("order_payments", "order_payments", ["order_id", "payment_sequential"], [col("order_id", required=True),
        col("payment_sequential", kind="integer", required=True), col("payment_type", required=True),
        col("payment_installments", kind="integer", required=True), col("payment_value", kind="numeric(12,2)", required=True)],
        [("order_id", "orders", "order_id")]),
    ("order_reviews", "order_reviews", ["review_id", "order_id"], [col("review_id", required=True), col("order_id", required=True),
        col("review_score", kind="smallint", required=True), col("comment_title", "review_comment_title"),
        col("comment_message", "review_comment_message"), col("review_created_at", "review_creation_date", "timestamp", True),
        col("review_answered_at", "review_answer_timestamp", "timestamp", True)], [("order_id", "orders", "order_id")]),
]


def generate():
    sql = ["-- Generated by scripts/build_core_load.py. Review with docs/core_model.md.",
           "-- Execute through scripts/load_core.py to register the run and publish atomically.",
           "SET LOCAL DateStyle = 'ISO, YMD';",
           "LOCK TABLE " + ", ".join("raw." + t for t in ["customers", "sellers", "products", "orders", "order_items", "order_payments", "order_reviews", "product_category_translation"]) + " IN SHARE MODE;"]
    for table, raw, keys, columns, refs in TABLES:
        if raw:
            source = f"SELECT r.ctid::text AS _ref, to_jsonb(r) AS _original, " + ", ".join(
                f"etl.clean(r.{src}) AS v_{name}" for name, src, _, _ in columns) + f" FROM raw.{raw} r"
        else:
            source = """SELECT 'translation:' || r.ctid::text AS _ref, to_jsonb(r) AS _original,
                etl.clean(r.product_category_name) AS v_category_name,
                etl.clean(r.product_category_name_english) AS v_category_name_english
                FROM raw.product_category_translation r
                UNION ALL
                SELECT 'product-category:' || etl.clean(r.product_category_name),
                jsonb_build_object('product_category_name', etl.clean(r.product_category_name)),
                etl.clean(r.product_category_name), NULL::text FROM raw.products r
                WHERE etl.clean(r.product_category_name) IS NOT NULL AND NOT EXISTS (
                  SELECT 1 FROM raw.product_category_translation t
                  WHERE etl.clean(t.product_category_name) = etl.clean(r.product_category_name))
                GROUP BY etl.clean(r.product_category_name)"""
        expressions, errors = [], []
        for name, src, kind, required in columns:
            v = "v_" + name
            cast = f"{v}::timestamp::date" if kind == "date" else f"{v}::{kind}"
            expressions.append(f"CASE WHEN etl.valid_value({v}, '{kind}') THEN {cast} END AS {name}")
            if required:
                errors.append(f"CASE WHEN {v} IS NULL THEN 'required:{name}' END")
            if kind != "text":
                errors.append(f"CASE WHEN NOT etl.valid_value({v}, '{kind}') THEN 'invalid_type:{name}:{kind}' END")
        key_expr = ", ".join(f"'{key}', v_{key}" for key in keys)
        sql.append(f"CREATE TEMP TABLE stage_{table} ON COMMIT DROP AS\nWITH normalized AS ({source})\n"
                   f"SELECT _ref, _original, jsonb_build_object({key_expr}) AS _key,\n  " + ",\n  ".join(expressions) +
                   ",\n  array_remove(ARRAY[" + ", ".join(errors) + f"]::text[], NULL) AS _errors FROM normalized;")
        for unique_keys, reason in [(keys, "duplicate_key")] + ([( ["customer_id"], "duplicate_customer_link")] if table == "orders" else []):
            grouped = ", ".join(unique_keys)
            present = " AND ".join(f"{k} IS NOT NULL" for k in unique_keys)
            match = " AND ".join(f"s.{k}=d.{k}" for k in unique_keys)
            sql.append(f"UPDATE stage_{table} s SET _errors = s._errors || ARRAY['{reason}:{grouped}'] "
                       f"FROM (SELECT {grouped} FROM stage_{table} WHERE {present} GROUP BY {grouped} "
                       f"HAVING COUNT(*) > 1) d WHERE {match};")
        # Parent stages are already validated because TABLES is dependency ordered.
        for field, parent, parent_key in refs:
            sql.append(f"UPDATE stage_{table} s SET _errors = s._errors || ARRAY['foreign_key:{field}:{parent}'] "
                       f"WHERE s.{field} IS NOT NULL AND NOT EXISTS (SELECT 1 FROM stage_{parent} p "
                       f"WHERE p.{parent_key} = s.{field} AND cardinality(p._errors)=0);")
        sql.append(f"CREATE INDEX ON stage_{table} ({', '.join(keys)}) WHERE cardinality(_errors)=0;")
        sql.append(f"ANALYZE stage_{table};")
        sql.append(f"INSERT INTO etl.rejected_rows(run_id,target_table,source_ref,source_key,source_record,errors) "
                   f"SELECT current_setting('etl.run_id')::uuid, '{table}', _ref, _key, _original, _errors "
                   f"FROM stage_{table} WHERE cardinality(_errors)>0;")
    sql += ["-- BEGIN PUBLICATION", "LOCK TABLE " + ", ".join("core." + t[0] for t in TABLES) + " IN SHARE ROW EXCLUSIVE MODE;"]
    for table, raw, keys, columns, refs in TABLES:
        names = [c[0] for c in columns]
        attributes = [c for c in names if c not in keys]
        match = " AND ".join(f"c.{k}=s.{k}" for k in keys)
        different = "ROW(" + ",".join("c." + a for a in attributes) + ") IS DISTINCT FROM ROW(" + ",".join("s." + a for a in attributes) + ")"
        sql.append(f"INSERT INTO etl.table_stats SELECT current_setting('etl.run_id')::uuid, '{table}', "
                   f"(SELECT COUNT(*) FROM stage_{table}), COUNT(*), "
                   f"(SELECT COUNT(*) FROM stage_{table} WHERE cardinality(_errors)>0), "
                   f"COUNT(*) FILTER (WHERE c.{keys[0]} IS NULL), "
                   f"COUNT(*) FILTER (WHERE c.{keys[0]} IS NOT NULL AND ({different})), "
                   f"COUNT(*) FILTER (WHERE c.{keys[0]} IS NOT NULL AND NOT ({different})) "
                   f"FROM stage_{table} s LEFT JOIN core.{table} c ON {match} WHERE cardinality(s._errors)=0;")
        change = "ROW(" + ",".join("target." + a for a in attributes) + ") IS DISTINCT FROM ROW(" + ",".join("excluded." + a for a in attributes) + ")"
        sql.append(f"INSERT INTO core.{table} AS target ({', '.join(names)}) "
                   f"SELECT {', '.join(names)} FROM stage_{table} WHERE cardinality(_errors)=0 "
                   f"ON CONFLICT ({', '.join(keys)}) DO UPDATE SET " + ", ".join(f"{a}=excluded.{a}" for a in attributes) +
                   f" WHERE {change};")
    return "\n\n".join(sql) + "\n"


if __name__ == "__main__":
    destination = ROOT / "model/02_load.sql"
    destination.write_text(generate(), encoding="utf-8")
    print(destination)
